function yearsGen(n) { return `${n} ${n % 10 === 1 && n % 100 !== 11 ? 'года' : 'лет'}`; }
function childText(c) {
  const who = c.g === 'f' ? 'дочь' : 'сын';
  if (c.age >= 18) {
    if (c.g === 'm' && c.age <= 20) return 'сын в армии';
    return c.g === 'f' ? 'взрослая дочь' : 'взрослый сын';
  }
  return `${who} ${yearsGen(c.age)}`;
}
const COLLECTIVE = ['', '', 'двое', 'трое', 'четверо'];
export function kidsText(children) {
  if (!children.length) return 'детей нет';
  if (children.length === 1) return childText(children[0]);
  const list = children.map(childText);
  return `${COLLECTIVE[children.length] || children.length} детей: ${list.slice(0, -1).join(', ')} и ${list[list.length - 1]}`;
}

function leftKids(k) {
  if (!k.length) return 'Детей нет.';
  if (k.length > 1) return `Остались ${kidsText(k)}.`;
  const c = k[0], t = childText(c);
  if (t === 'сын в армии') return 'Сын служит в армии.';
  return `${c.g === 'f' ? 'Осталась' : 'Остался'} ${t}.`;
}

export function genFamily(rng, o) {
  const a = o.age;
  let status;
  const r = rng.next();
  if (a < 24) status = r < 0.72 ? 'single' : 'married';
  else if (a < 33) status = r < 0.55 ? 'married' : r < 0.72 ? 'divorced' : 'single';
  else if (a < 46) status = r < 0.6 ? 'married' : r < 0.85 ? 'divorced' : r < 0.9 ? 'widowed' : 'single';
  else status = r < 0.62 ? 'married' : r < 0.82 ? 'divorced' : r < 0.94 ? 'widowed' : 'single';
  let nk = 0;
  if (status !== 'single') {
    const maxK = a < 26 ? 1 : a < 32 ? 2 : 3;
    nk = rng.weighted([{ n: 0, w: status === 'married' && a < 30 ? 3 : 1.5 }, { n: 1, w: 4 }, { n: 2, w: 3 }, { n: 3, w: 0.6 }].filter((x) => x.n <= maxK)).n;
  } else if (o.gender === 'f' && a > 25 && rng.chance(0.25)) nk = 1; // одна растит ребёнка
  const children = [];
  for (let i = 0; i < nk; i++) {
    const maxAge = Math.max(1, a - 20);
    children.push({ g: rng.chance(0.5) ? 'm' : 'f', age: rng.int(Math.max(1, maxAge - 14), maxAge) });
  }
  children.sort((x, y) => y.age - x.age);
  const spouseJob = status === 'married' ? rng.pick(o.gender === 'f' ? SPOUSE_JOB_M : SPOUSE_JOB_W) : null;
  return { status, married: status === 'married', kids: children.length, children, spouseJob, note: '' };
}

export function familyNote(rng, o) {
  const f = o.family, k = f.children, kt = kidsText(k);
  const s = { s: o };
  const m = o.gender === 'm';
  switch (f.status) {
    case 'married':
      if (!k.length) return fmt(rng.pick(m
        ? ['Женат %y% год, детей пока нет — «не на что».', 'Женат. Жена — %job%. Детей нет, на квартиру копят шестой год.']
        : ['Замужем, детей пока нет. Муж — %job%.', 'Замужем %y% год. Муж — %job%; о детях говорят «потом, когда наладится».']),
        { ...s, vars: { job: f.spouseJob, y: rng.pick(['второй', 'третий', 'пятый']) } });
      return fmt(rng.pick(m
        ? ['Женат, %kt%. Жена — %job%.', 'Женат, %kt%. Жена — %job%, видятся по выходным, если выходные бывают.', 'Женат второй раз; %kt%. Жена — %job%.']
        : ['Замужем, %kt%. Муж — %job%.', 'Замужем, %kt%. Муж — %job%; семью тянет в основном она.']),
        { ...s, vars: { kt, job: f.spouseJob } });
    case 'divorced':
      if (!k.length) return fmt(rng.pick(m
        ? ['Разведён. Говорит, что с такой службой это закономерно.', 'Разведён: жена ушла к коммерсанту с тремя ларьками на Рынке.']
        : ['Разведена. Бывший муж «ищет себя» в Москве третий год.', 'Разведена; о бывшем муже говорит коротко и непечатно — то есть молчит.']), s);
      return fmt(rng.pick(m
        ? ['Разведён: жена ушла к коммерсанту с ларьками на Рынке и забрала детей; %kt%. Платит алименты — когда платят ему.', 'Разведён, %kt% — живут с бывшей женой. Видится по воскресеньям, если не на смене.']
        : ['Разведена, одна растит детей: %kt%. Бывший муж алименты не платит — «нету».', 'Разведена; %kt%. С детьми сидит её мать, пока она на сутках.']),
        { ...s, vars: { kt } });
    case 'widowed':
      return fmt(rng.pick(m
        ? ['Вдовец: жена умерла в девяносто третьем. %ktc%', 'Вдовец. Жену похоронил три года назад — сердце. %ktc%']
        : ['Вдова: муж погиб на шахте в девяносто первом. %ktc%', 'Вдова. Муж разбился на трассе — дальнобойщиком был. %ktc%']),
        { ...s, vars: { ktc: leftKids(k) } });
    default:
      if (k.length) return fmt('Не замужем, одна растит ребёнка: %kt%.', { ...s, vars: { kt } });
      return fmt(rng.pick(m
        ? ['Холост, живёт с матерью в однокомнатной хрущёвке.', 'Не женат, снимает комнату в общежитии ткацкой фабрики — со всеми вытекающими.', 'Холост. Говорит, что сначала квартира, потом жена. Квартиры не предвидится.']
        : ['Не замужем, живёт с матерью и котом.', 'Не замужем. Говорит, что с такой работой это и есть брак.', 'Не замужем, снимает комнату у старушки на Черёмушках.']), s);
  }
}

