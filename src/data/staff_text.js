export function genBio(rng, o, ctx = {}) {
  const h = hasTraits(o);
  const vars = {
    sy: o.serviceSince, school: rng.int(3, 41),
    ay1: 0, ay2: 0,
  };
  if (h.afghan) {
    const by = 1996 - o.age;
    let y1 = Math.min(1987, Math.max(1980, by + rng.int(18, 20)));
    if (o.age > 37) y1 = rng.int(1981, 1986);
    if (o.gender === 'f') y1 = rng.int(1982, 1986);
    vars.ay1 = y1; vars.ay2 = Math.min(1989, y1 + 2);
  }
  const ctxT = { s: o, vars };
  const sentences = [];
  const local = h.local ? (DISTRICT_PREP[ctx.localDistrict] || 'на Черёмушках') : null;
  if (local && rng.chance(0.8)) sentences.push(fmt(`Местн{ый|ая}: {вырос|выросла} ${local}, там же и живёт.`, ctxT));
  else if (rng.chance(0.3)) sentences.push(fmt(`{Родился|Родилась} ${rng.pick(HOMETOWNS)}, в город {приехал|приехала} после школы.`, ctxT));
  const paths = PATHS.filter((p) => p.when(o, h));
  if (paths.length) {
    // приоритет — военные и «салажьи» пути
    const forced = paths.filter((p) => /afghan|chechnya_conscript|rookie_path/.test(p.id));
    const pool = forced.length ? forced : paths;
    const p = rng.weighted(pool);
    sentences.push(fmt(rng.pick(p.t), ctxT));
  }
  if (!h.rookie && rng.chance(0.55)) sentences.push(fmt(rng.pick(SERVICE[o.gender]), ctxT));
  if (h.chechnya && !(o.gender === 'm' && o.age <= 23)) {
    const variants = o.gender === 'f' ? [CHECHNYA_TRIP[0], CHECHNYA_TRIP[1]] : CHECHNYA_TRIP;
    sentences.push(fmt(rng.pick(variants), ctxT));
  }
  sentences.push(familyNote(rng, o));
  const qs = QUIRKS.filter((q) => q.when(o, h));
  if (qs.length && sentences.length < 4) sentences.push(fmt(rng.weighted(qs).t, ctxT));
  // 2–4 предложения-блока
  while (sentences.length > 4) sentences.splice(rng.int(0, sentences.length - 3), 1);
  return sentences.join(' ');
}

