export function countWord(n) { return n <= 0 ? 'Никого' : n < COUNT.length ? COUNT[n] : 'Много их'; }
export function zoneGender(short) { return GEN_M[short] || 'm'; }

/** Винительный падеж для уменьшительного имени («Санька» → «Саньку»), иначе null */
export function accusative(name) {
  if (!name) return null;
  if (/[кгхжшщч]а$/.test(name) || /[^и]а$/.test(name)) return name.replace(/а$/, 'у');
  if (/я$/.test(name)) return name.replace(/я$/, 'ю');
  return null;
}

function fill(t, sg, subjG, vars) {
  let s = t.replace(/\{([^|}]*)\|([^}]*)\}/g, (_, m, f) => (sg === 'f' ? f : m));
  s = s.replace(/\[([^|\]]*)\|([^\]]*)\]/g, (_, m, f) => (subjG === 'f' ? f : m));
  for (const k of Object.keys(vars)) s = s.split('$' + k).join(vars[k]);
  return s;
}

/** Менеджер реплик с ограничением частоты (на актора и на сторону). */
export class Barks {
  constructor(cb) { this.cb = cb; this.lastSide = { police: -9, enemy: -9 }; }
  /** Сказать. key — категория; opts: {force, n, subj (актор), vars, chance, dur} → текст или null */
  say(actor, key, opts = {}) {
    if (!actor || !actor.alive) return null;
    const list = P[key]; if (!list) return null;
    const c = actor.data.cb || {}; const now = this.cb.t;
    const side = c.side || 'police';
    const talk = c.talkative ?? 1;
    if (!opts.force) {
      if (opts.chance !== undefined && !this.cb.rng.chance(opts.chance * talk)) return null;
      if ((c.nextBark || 0) > now) return null;
      if (now - this.lastSide[side] < 0.7) return null;
    }
    const subj = opts.subj || null;
    const vars = Object.assign({}, opts.vars || {});
    if (subj) {
      vars.n = vars.n || this.cb.callName(subj, actor);
      if (key === 'revenge') { const acc = accusative(vars.n); if (!acc) return null; vars.acc = acc; }
    }
    let t = this.cb.rng.pick(list);
    if (key === 'revenge' && !vars.acc) return null;
    const subjG = subj ? (subj.look && subj.look.gender) || 'm' : (vars.subjG || 'm');
    const text = fill(t, (actor.look && actor.look.gender) || 'm', subjG, vars).replace(/\s+/g, ' ').trim();
    if (!text || /\$|undefined|NaN/.test(text)) return null;
    actor.say(text, opts.dur || Math.min(3.2, 1.2 + text.length * 0.05));
    c.nextBark = now + (opts.force ? 1.2 : 2.6 / Math.max(0.3, talk)) + this.cb.rng.next() * 1.5;
    this.lastSide[side] = now;
    this.cb.onBark(actor, text, key);
    return text;
  }
}
