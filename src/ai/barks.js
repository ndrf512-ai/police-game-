const recent = new Map(); // key -> [индексы последних выборов]

function pickWeighted(rng, arr) {
  let s = 0; for (const x of arr) s += x.w;
  let r = rng.next() * s;
  for (const x of arr) { r -= x.w; if (r <= 0) return x; }
  return arr[arr.length - 1];
}

/** Подстановка шаблона. ctx: {speaker, listener, player, extra} */
export function fillText(text, ctx = {}) {
  const sp = ctx.speaker || {}, li = ctx.listener || {}, pl = ctx.player || {}, ex = ctx.extra || {};
  const G = { S: sp.gender, L: li.gender, P: pl.gender, V: ex.vgender, D: ex.dgender };
  let s = String(text).replace(/\{([SLPVD]):([^{}|]*)\|([^{}]*)\}/g, (_, k, m, f) => (G[k] === 'f' ? f : m));
  const vals = {
    rank: pl.rank || 'майор', plast: pl.lastName || '', pname: pl.firstName ? `${pl.firstName} ${pl.patronymic || ''}`.trim() : '',
    srank: sp.rank || 'сержант', slast: sp.lastName || '', sname: sp.colloq || sp.firstName || '',
    lrank: li.rank || '', llast: li.lastName || '', lname: li.colloq || li.firstName || 'друг',
    dead: ex.dead || 'наш', deadname: ex.deadname || ex.dead || 'наш', news: ex.news || 'опять про Чечню', n: ex.n ?? 1,
    det: ex.det || 'никого', nick: ex.nick || 'Серый', title: ex.title || '', callsign: ex.callsign || 'Сокол',
  };
  s = s.replace(/\{(\w+)\}/g, (_, k) => (vals[k] !== undefined && vals[k] !== null ? String(vals[k]) : ''));
  return s.replace(/\s{2,}/g, ' ').replace(/\s+([,.!?…])/g, '$1').trim();
}

function entryOk(e, ctx) {
  const sp = ctx.speaker || {};
  const tr = sp.traits || [];
  if (e.g && sp.gender && e.g !== sp.gender) return false;
  if (e.pg && ctx.player && e.pg !== ctx.player.gender) return false;
  if (e.night === true && !ctx.night) return false;
  if (e.night === false && ctx.night) return false;
  if (e.ntr && e.ntr.some((t) => tr.includes(t))) return false;
  if (e.tr && !e.tr.some((t) => tr.includes(t) || (t === 'driver' && sp.role === 'driver'))) return false;
  return true;
}

/**
 * Реплика по ключу ситуации с учётом черт/рода/времени. Возвращает строку или null.
 * ctx: {rng, speaker:{gender,traits,rank,lastName,firstName,colloq,role}, listener, player:{gender,rank,lastName,...}, night, extra}
 */
export function bark(key, ctx = {}) {
  const list = BARKS[key];
  if (!list || !list.length || !ctx.rng) return null;
  const rec = recent.get(key) || [];
  const cands = [];
  list.forEach((raw, i) => {
    const e = typeof raw === 'string' ? { t: raw } : raw;
    if (!entryOk(e, ctx)) return;
    let w = e.w ?? 1;
    if (e.tr) w *= 3;               // характерные реплики — в приоритете
    if (rec.includes(i)) w *= 0.04; // не повторяться
    cands.push({ i, e, w });
  });
  if (!cands.length) return null;
  const c = pickWeighted(ctx.rng, cands);
  rec.push(c.i); if (rec.length > Math.min(6, Math.floor(list.length / 2))) rec.shift();
  recent.set(key, rec);
  return fillText(c.e.t, ctx);
}

