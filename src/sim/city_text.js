// Описание ранения в эфире: сотрудник может быть женщиной — род по нему, а не по говорящему.
export function woundWord(o, sev) {
  const f = o && o.gender === 'f';
  if (sev >= 3) return f ? 'тяжело ранена' : 'тяжело ранен';
  if (sev === 2) return f ? 'ранена' : 'ранен';
  return f ? 'легко ранена, зацепило' : 'легко ранен, зацепило';
}
